import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mkdirSync } from 'node:fs'

test('borradores, corrección completa, copia y respaldo', async ({ page }) => {
  const errores: string[] = []
  page.on('pageerror', e => errores.push(e.message))
  await page.goto('/')
  await page.getByLabel('Buscar ejercicio').fill('A5 ')
  // La búsqueda también permite acceder por número sin recorrer 80 entradas.
  await page.getByLabel('Buscar ejercicio').fill('longitud par')
  await page.getByRole('button', { name: /^A5 / }).click()
  await page.getByLabel('Tu expresión regular').fill('((a|b)(a|b))*')
  await page.getByLabel('Desarrollo y justificación').fill('Alterno entre un estado par y uno impar; el inicial acepta ε.')
  await page.getByRole('button', { name: 'Adjuntar desde el editor', exact: true }).click()
  await page.getByRole('button', { name: 'Guardar esta copia' }).click()
  await page.getByRole('button', { name: 'Verificar respuesta' }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Verificado' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Tu expresión regular')).toHaveValue('((a|b)(a|b))*')
  await page.getByRole('button', { name: 'Editar este diagrama' }).click()
  await expect(page.getByRole('heading', { name: 'Editor de autómatas' })).toBeAttached()
  await page.getByRole('button', { name: 'Volver a la respuesta y adjuntar' }).click()
  await expect(page.getByLabel('Tu expresión regular')).toHaveValue('((a|b)(a|b))*')
  await page.getByRole('button', { name: 'Ver texto', exact: true }).click()
  await expect(page.getByLabel('Texto listo para copiar')).toContainText('MI RESPUESTA')
  await expect(page.getByLabel('Texto listo para copiar')).toContainText('Inicial:')
  await page.getByRole('button', { name: 'Mi progreso', exact: true }).click()
  const descarga = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar respaldo' }).click()
  expect((await descarga).suggestedFilename()).toMatch(/automatalab-respaldo.*json/)
  expect(errores).toEqual([])
})

test('parcial: conserva el ítem, reloj, entrega e historial al volver del editor', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Parciales', exact: true }).click()
  await page.getByLabel('Tu nombre').fill('Estudiante de prueba')
  await page.getByRole('button', { name: 'Iniciar reloj' }).click()
  await page.getByRole('button', { name: /Ejercicio 2.*60 pts/ }).click()
  await page.getByRole('button', { name: 'Dibujar en el editor' }).click()
  await page.getByRole('button', { name: 'Agregar estado', exact: true }).click()
  await page.getByRole('button', { name: 'Volver a la respuesta y adjuntar' }).click()
  await expect(page.getByRole('button', { name: /Ejercicio 2.*60 pts/ })).toHaveAttribute('aria-current', 'step')
  await page.getByLabel('Desarrollo y justificación').fill('Borrador de procedimiento')
  await page.reload()
  await expect(page.getByLabel('Desarrollo y justificación')).toHaveValue('Borrador de procedimiento')
  await page.getByRole('button', { name: 'Entregar parcial', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Entrega guardada' })).toBeVisible()
  await expect(page.getByLabel('Desarrollo y justificación')).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Entrega guardada' })).toBeVisible()
  const descargar = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Descargar entrega', exact: true }).click()
  expect((await descargar).suggestedFilename()).toMatch(/entrega.txt/)
  await page.getByRole('button', { name: 'Volver a practicar' }).click()
  await expect(page.getByLabel('Desarrollo y justificación')).toBeEnabled()
  await expect(page.getByText('Entregas anteriores (1)')).toBeVisible()
})

test('banco completo, LISP sin soluciones automáticas y uso por teclado del editor', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: /^F LISP/ }).click()
  await page.getByLabel('Tu código LISP y casos de prueba').fill('(defun cuadrado (n) (* n n))')
  await page.getByRole('button', { name: /^C ER/ }).click()
  await expect(page.getByRole('button', { name: 'Mostrar solución de referencia' })).toBeVisible()
  await expect(page.getByRole('img', { name: 'Diagrama de transiciones' })).toHaveCount(0)
  await page.getByRole('button', { name: /^F LISP/ }).click()
  await expect(page.getByLabel('Tu código LISP y casos de prueba')).toHaveValue('(defun cuadrado (n) (* n n))')
  await page.getByRole('button', { name: 'Editor', exact: true }).click()
  await page.getByRole('button', { name: 'Agregar estado', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Elegir estado')).not.toHaveValue('')
  await page.getByLabel('Nombre', { exact: true }).fill('nuevo')
  const celda = page.getByRole('cell', { name: /nuevo, símbolo a:/ })
  await celda.focus()
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('Destinos de nuevo con a')).toBeFocused()
})

test('inspección de accesibilidad, escritorio, celular y temas', async ({ page }) => {
  mkdirSync('.impeccable/review', { recursive: true })
  await page.goto('/')
  await page.evaluate(() => document.fonts.ready)
  await page.screenshot({ path: '.impeccable/review/desktop.png', fullPage: true })
  for (const nombre of ['Práctica', 'Parciales', 'Mi progreso', 'Editor', 'Conversiones']) {
    await page.getByRole('button', { name: nombre, exact: true }).click()
    const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), nombre).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), nombre).toBe(true)
  }
  await page.getByRole('button', { name: 'Parciales', exact: true }).click()
  await page.screenshot({ path: '.impeccable/review/examen-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Práctica', exact: true }).click()
  await page.screenshot({ path: '.impeccable/review/mobile.png', fullPage: true })
  for (const tema of ['claro', 'oscuro', 'papel']) {
    await page.getByRole('combobox', { name: 'Tono de la página' }).selectOption(tema)
    const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => n.target) })), tema).toEqual([])
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), tema).toBe(true)
  }
  await page.screenshot({ path: '.impeccable/review/mobile-papel.png', fullPage: true })
  await page.getByRole('button', { name: 'Parciales', exact: true }).click()
  await page.screenshot({ path: '.impeccable/review/examen-mobile.png', fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
